"""Inventory of hard-coded thresholds and tunables: module-level UPPER_CASE numbers / strings / regexes, and numeric
keyword defaults of functions. Every one is a choice a reviewer can ask a sensitivity analysis for.

    python scripts/list_constants.py [--out docs/constants_inventory.md]
"""
from __future__ import annotations
import argparse
import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PACKAGES = ["qubo_auto", "acceptance"]
SKIP = {"tests", "poster", "results"}


def literal(node):
    try:
        v = ast.literal_eval(node)
    except Exception:
        if isinstance(node, ast.Call) and getattr(node.func, "attr", "") == "compile":
            return "regex"
        return None
    if isinstance(v, bool) or v is None:
        return None
    if isinstance(v, (int, float)):
        return v
    if isinstance(v, (set, tuple, list, dict)) and len(str(v)) <= 60:
        return v
    return None


def scan(path: Path):
    tree = ast.parse(path.read_text())
    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            name = node.targets[0].id
            v = literal(node.value)
            if name.isupper() and v is not None:
                yield "constant", name, v, node.lineno
    for node in ast.walk(tree):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            args = node.args
            pos = args.posonlyargs + args.args
            for a, d in zip(pos[len(pos) - len(args.defaults):], args.defaults):
                v = literal(d)
                if isinstance(v, (int, float)):
                    yield "default", f"{node.name}({a.arg})", v, node.lineno
            for a, d in zip(args.kwonlyargs, args.kw_defaults):
                v = literal(d) if d is not None else None
                if isinstance(v, (int, float)):
                    yield "default", f"{node.name}({a.arg})", v, node.lineno


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out")
    a = ap.parse_args()
    rows = []
    for pkg in PACKAGES:
        for f in sorted((ROOT / pkg).rglob("*.py")):
            if SKIP & set(f.relative_to(ROOT).parts):
                continue
            for kind, name, value, line in scan(f):
                rows.append((str(f.relative_to(ROOT)), line, kind, name, value))
    out = ["# Hard-coded thresholds and tunables", "",
           f"{len(rows)} entries ({sum(r[2] == 'constant' for r in rows)} module constants, "
           f"{sum(r[2] == 'default' for r in rows)} numeric keyword defaults). Generated by `scripts/list_constants.py`; "
           "regenerate after changing code. A sensitivity analysis is still missing for every row that decides what "
           "passes a gate or what data is kept.", "",
           "| File | Line | Kind | Name | Value |", "|---|--:|---|---|---|"]
    for f, line, kind, name, value in rows:
        out.append(f"| {f} | {line} | {kind} | `{name}` | `{str(value)[:50]}` |")
    text = "\n".join(out) + "\n"
    if a.out:
        Path(a.out).write_text(text)
    print(f"{len(rows)} entries" + (f" -> {a.out}" if a.out else ""))
    if not a.out:
        print(text)


if __name__ == "__main__":
    main()
